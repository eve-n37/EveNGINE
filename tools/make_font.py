def cells():
    out = [ascii_glyphs[chr(c)] for c in range(32, 128)]
    out += [latin1[c] for c in range(0xA0, 0x100)]
    out += [cell for _, cell in SYMBOLS]
    out += [g()] * (256 - len(out))
    for cell in out:
        assert len(cell) == 8 and all(len(r) == 6 for r in cell), cell
    return out


def pixels():
    W, H = 192, 64
    alpha = [[0] * W for _ in range(H)]
    for i, cell in enumerate(cells()):
        ox, oy = (i % 32) * 6, (i // 32) * 8
        for y, row in enumerate(cell):
            for x, ch in enumerate(row):
                if ch == "#":
                    alpha[oy + y][ox + x] = 255
    return W, H, alpha


if __name__ == "__main__":
    W, H, alpha = pixels()
    data = bytearray()
    for row in alpha:
        for a in row:
            data += bytes([255, 255, 255, a])
    header = (
        f"P7\nWIDTH {W}\nHEIGHT {H}\nDEPTH 4\nMAXVAL 255\nTUPLTYPE RGB_ALPHA\nENDHDR\n"
    )
    (root / "editor/examples/font.pam").write_bytes(header.encode() + bytes(data))
    try:
        from PIL import Image

        Image.frombytes("RGBA", (W, H), bytes(data)).save(root / "tools/font.png")
    except ImportError:
        pass
    print("Wrote", root / "editor/examples/font.pam")
    print("Symbols:", "".join(c for c, _ in SYMBOLS))
