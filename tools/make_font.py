thin_accents = {
    "grave": ".#...",
    "acute": "...#.",
    "circumflex": "..#..",
    "tilde": ".##.#",
    "diaeresis": ".#.#.",
    "caron": ".#.#.",
}
dotless_i = g(".##..", "..#..", "..#..", "..#..", ".###.", top=2)


def accented(base, accent):
    if base in tall_caps:
        return [thin_accents[accent].ljust(6, ".")] + g(*tall_caps[base], top=1)[1:]
    if base in short_caps:
        body = g(*short_caps[base], top=2)
    elif base == "i":
        body = list(dotless_i)
    else:
        body = list(ascii_glyphs[base])
    mark = accents[accent]
    return [mark[0].ljust(6, "."), mark[1].ljust(6, ".")] + body[2:]


def cedilla(base):
    cell = list(ascii_glyphs[base])
    cell[7] = ".##...."[:6]
    return cell


